setmetatable(PRETTY_LOCALIZATION, {
    __call = function(self, key)
        if not self[key] then
            return "NOT LOCALE"
        end
        local locale = GetLocale()
        if locale == "frFR" then
            return self[key].frFR
        elseif locale == "ruRU" then
            return self[key].ruRU
        elseif locale == "zhCN" or locale == "zhTW" then
            return self[key].zhCN
        elseif locale == "enUS" then
            return self[key].enUS
        elseif locale == "enGB" then
            return self[key].enGB
        else
            return key
        end
    end
});

for key in next, PRETTY_LOCALIZATION do
    _G[key] = PRETTY_LOCALIZATION(key);
end
